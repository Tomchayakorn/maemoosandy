import { DAY_INFO } from "../astrology/taksa";
import { thaiNow } from "../astrology/now-th";
import type { Variety } from "../astrology/variety";
import { shortThaiName, type DrawnCardView } from "./deck";

/**
 * The AI prompt for the 3-card tarot reading ("สื่อจิต 3 ใบ"). The three cards and their positions (อดีต · ปัจจุบัน · อนาคต) are exactly as drawn;
 * the prompt adds the CURRENT Thai date and time (from the server's clock, passed in by the caller) so the cards are read for this moment, a
 * per-request variety angle, and a closing about the "สวดเสริมดวงชะตากับแม่มู" whose tone follows how the cards turned out.
 */
export function buildTarotPrompt(question: string, cards: DrawnCardView[], opts: { now?: Date; variety?: Variety } = {}): string {
  const now = thaiNow(opts.now ?? new Date());
  const dayColor = DAY_INFO[now.astroDay].color;
  const lines = cards.map(
    (c, i) =>
      `${i + 1}. ตำแหน่ง "${c.position}": ${c.nameTh}${c.isReversed ? " — ไพ่กลับหัว" : " — ไพ่หัวตั้ง"}\n   ความหมายหลัก: ${c.meaning}`,
  );

  const v = opts.variety;
  const varietyBlock = v
    ? `\nมุมเล่าครั้งนี้ (เพื่อให้คำทำนายสดใหม่ไม่ซ้ำสูตรเดิม): ${v.opening}; ${v.lens}\n` +
      `ใช้ถ้อยคำและภาพเปรียบเทียบใหม่ทุกครั้ง หลีกเลี่ยงประโยคเปิดสูตรเดิมๆ แต่ต้องมีหัวข้อครบทุกข้อตามโครงด้านล่าง\n`
    : "";

  return `ผู้ถามตั้งจิตอธิษฐานแล้วเปิดไพ่ยิปซี 3 ใบ (อดีต · ปัจจุบัน · อนาคต)

<question>${question}</question>

ไพ่ที่เปิดได้ (ตำแหน่งและความหมายตามนี้ ห้ามสลับหรือเปลี่ยน):
${lines.join("\n")}

ข้อมูลเวลาปัจจุบัน ณ ขณะที่ถาม (ใช้ตามนี้ ห้ามเดาวันเวลาเอง):
- ตอนนี้คือ ${now.label} (เวลาประเทศไทย)
- วันทางโหราศาสตร์ที่กำลังดำเนินอยู่: ${now.astroDayTh} สีประจำวันนี้: ${dayColor}
${varietyBlock}
ช่วยทำนายให้ตรงกับคำถาม โดยอ่านไพ่ทั้งสามใบตามตำแหน่งเดิม แล้วเชื่อมกับวันและเวลาปัจจุบันว่าพลังของไพ่ส่งผลอย่างไรในจังหวะนี้ มีหัวข้อดังนี้ตามลำดับ ข้อความในวงเล็บคือคำอธิบายสำหรับแม่มู ไม่ต้องคัดลอกลงในหัวข้อ
## ภาพรวมของคำถาม
## อดีต: ${shortThaiName(cards[0].nameTh)}
## ปัจจุบัน: ${shortThaiName(cards[1].nameTh)}
## อนาคต: ${shortThaiName(cards[2].nameTh)}
## จังหวะเวลานี้กับไพ่ทั้งสามใบ (ดูตอนนี้คือ${now.weekdayTh} ช่วง${now.dayPart} พลังของไพ่ทั้งสามเชื่อมกับวันและเวลานี้อย่างไร)
## สิ่งที่ควรทำในจังหวะนี้ (2-3 ข้อ เป็นรายการขึ้นต้น "- " เพื่อเปิดรับโอกาสหรือประคองสถานการณ์ ทำได้จริงในวันนี้)
## สิ่งที่ควรหลบหลีกหรือระวังในจังหวะนี้ (2-3 ข้อ เป็นรายการขึ้นต้น "- " บอกอย่างนุ่มนวล ไม่ขู่)
## คำตอบจากแม่มู (สรุปคำตอบของคำถามอย่างตรงไปตรงมา)
## คำแนะนำเสริมดวงจากแม่มู (เสริมดวงเล็กๆ 2-3 ข้อ แล้วปิดท้ายด้วยย่อหน้าเรื่อง "การสวดเสริมดวงชะตากับแม่มูแซนดี้" ตามหลักด้านล่าง และจบด้วยคำอวยพรสั้นๆ)

หลักของย่อหน้า "การสวดเสริมดวงชะตากับแม่มูแซนดี้" ให้ดูภาพรวมของไพ่ทั้งสามใบจากความหมายที่ให้ไว้ (ถ้าผสมกัน ให้ยึดทิศทางของใบปัจจุบันและใบอนาคตเป็นหลัก) แล้วปรับโทน:
- ถ้าภาพรวมโน้มไปทางติดขัด มีอุปสรรค หรือดวงตก: แนะนำอย่างอบอุ่นว่าการสวดเสริมดวงชะตากับแม่มูช่วยปัดเป่าอุปสรรค ผ่อนหนักให้เป็นเบา และเปิดทางให้ราบรื่นขึ้น พร้อมให้กำลังใจว่าอุปสรรคผ่านไปได้
- ถ้าภาพรวมดีหรือมีโชคลาภอยู่แล้ว: แนะนำว่าการสวดเสริมดวงชะตากับแม่มูช่วยหนุนดวงให้ดียิ่งขึ้นไปอีก ต่อยอดความสำเร็จ และรักษาพลังบวกให้ต่อเนื่อง
ข้อควรระวังในย่อหน้านี้: เป็นเพียงทางเลือกที่ผู้ถามสนใจก็สอบถามแม่มูได้ ห้ามกดดัน ห้ามเร่งรัด ห้ามบอกหรือสื่อว่าถ้าไม่สวดจะเกิดเรื่องร้าย ห้ามรับประกันผลลัพธ์ และห้ามระบุราคา ช่องทาง หรือเงื่อนไขการสวดที่ไม่ได้ให้ไว้ในข้อมูลนี้

ห้ามอ้างวันพระ ข้างขึ้นข้างแรม ดาวเคราะห์จร ฤกษ์ หรือเหตุการณ์ในปฏิทินที่ไม่ได้ให้ไว้ในข้อมูลด้านบน
ความยาวรวมประมาณ 550-750 คำ`;
}
