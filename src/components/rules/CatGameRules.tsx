import { CAT_COUNT, CAT_GAME_COST, CAT_REWARDS } from "@/lib/cat-game/config";
import { RuleList, RuleSection } from "./RuleParts";

const n = (v: number) => v.toLocaleString("th-TH");

/** Rules of "น้องเหมียว 9 ชีวิต". Numbers come from the same constants the game uses. */
export function CatGameRules() {
  return (
    <>
      <RuleSection title="1. วิธีเล่นและค่าเล่น">
        <RuleList>
          <li>เลือกจิ้มน้องเหมียว <b>1 ตัวจาก {CAT_COUNT} ตัว</b> (ส้ม 3 · ดำ 3 · ขาว 3) เพื่อลุ้นเหรียญรางวัลแบบเซอร์ไพรส์</li>
          <li>ค่าเล่น <b>{CAT_GAME_COST} เหรียญต่อรอบ</b> หักตอนจิ้มเลือก ผลสุ่มและการหักเหรียญทำที่ระบบหลังบ้านรอบละครั้ง</li>
          <li>เหรียญไม่พอ ระบบจะไม่เล่นและไม่หักเหรียญ หากการเชื่อมต่อขัดข้องก่อนได้ผล เหรียญจะไม่ถูกหักซ้ำ</li>
        </RuleList>
      </RuleSection>

      <RuleSection title="2. เล่นได้วันละ 1 ครั้ง">
        <RuleList>
          <li>เล่นได้ <b>วันละ 1 ครั้งต่อผู้เล่น</b> นับตามวันปฏิทินเวลาไทย สิทธิ์ใหม่เริ่มตั้งแต่เวลา 00:00 น.</li>
          <li>ระบบตรวจสิทธิ์ที่ฐานข้อมูล กดซ้ำ เปิดหลายแท็บ หรือหลายเครื่องก็เล่นเกินโควตาไม่ได้ และไม่มีการหักเหรียญเมื่อสิทธิ์วันนี้หมด</li>
        </RuleList>
      </RuleSection>

      <RuleSection title="3. รางวัลและโอกาสออก">
        <RuleList>
          <li>
            รางวัลมี 5 ระดับ: {CAT_REWARDS.map((r) => n(r)).join(" / ")} เหรียญ แต่ละระดับมีโอกาสออก <b>เท่ากัน ระดับละ 20%</b> ไม่ว่าจะเลือกน้องเหมียวตัวไหนหรือสีอะไร
          </li>
          <li>เหรียญรางวัลทั้งหมดเข้า <b>กระเป๋าเหรียญหลัก</b> ทันที ไม่มีการแบ่งเข้ายอดสะสมอื่น</li>
          <li>เป็นเกมสุ่มโชค ผลเป็นการสุ่มรอบต่อรอบ ไม่มีวิธีเลือกตัวที่ให้รางวัลมากกว่า</li>
        </RuleList>
      </RuleSection>

      <RuleSection title="4. การถอนเงิน">
        <RuleList>
          <li>เกมนี้ไม่มีระบบถอนเป็นเงินโดยตรง เหรียญที่ได้อยู่ในกระเป๋าหลัก ใช้เล่นเกมหรือดูดวงต่อได้</li>
          <li>เงื่อนไขการถอนของเกมกงล้อและเกมเปิดไพ่เป็นไปตามกติกาของแต่ละเกม (ดูได้ที่ปุ่ม “กติกา &amp; การถอน” ในเกมนั้น)</li>
          <li>หากพบปัญหาการใช้งาน ติดต่อแอดมินผ่านปุ่ม LINE ระบบสงวนสิทธิ์ตรวจสอบและระงับการใช้งานที่ผิดปกติหรือไม่สุจริต</li>
        </RuleList>
      </RuleSection>
    </>
  );
}
