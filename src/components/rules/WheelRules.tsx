import { WHEEL_SPIN_COST } from "@/lib/pricing";
import { HOT_STREAK_ROUNDS } from "@/lib/wheel/hot-streak";
import { JACKPOT_EVERY_PAID_SPINS_DISPLAY as JACKPOT_EVERY_PAID_SPINS } from "@/lib/wheel/display";
import { BUFF_ROUNDS } from "@/lib/wheel/luck-card";
import { WHEEL_CASH_BIG, WHEEL_CASH_LIMITS, WHEEL_CASH_PCT, WHEEL_CASH_SMALL } from "@/lib/wheel/cash";
import { RuleList, RuleSection } from "./RuleParts";

const n = (v: number) => v.toLocaleString("th-TH");

/** Rules of the lucky wheel. Numbers come from the same constants the game uses (client-safe modules only). */
export function WheelRules() {
  return (
    <>
      <RuleSection title="1. ค่าเล่นและสิทธิ์หมุน">
        <RuleList>
          <li>หมุนฟรีได้เมื่อมี “สิทธิ์หมุนฟรี” (สมาชิกใหม่ได้ 1 สิทธิ์ และเช็กอินรับเพิ่มได้วันละ 1 สิทธิ์ ตามวันปฏิทินเวลาไทย)</li>
          <li>เมื่อไม่มีสิทธิ์หมุนฟรี การหมุนจะหักครั้งละ <b>{n(WHEEL_SPIN_COST)} เหรียญ</b> หมุนต่อได้ไม่จำกัดจำนวนครั้ง ตราบใดที่เหรียญพอ</li>
          <li>ผลการสุ่มและการหักเหรียญทำที่ระบบหลังบ้านทั้งหมด หากเหรียญไม่พอ ระบบจะไม่หมุนและไม่หักเหรียญ</li>
        </RuleList>
      </RuleSection>

      <RuleSection title="2. รางวัลบนกงล้อ">
        <RuleList>
          <li>รางวัลเหรียญ 20 / 40 / 120 / 400 เหรียญ เข้ากระเป๋าทันที (ใช้เล่นเกมหรือดูดวงต่อได้)</li>
          <li>สิทธิ์ดูดวงฟรี และ “การ์ด +ความเฮง”</li>
          <li>ช่อง “ลองใหม่” คือไม่ได้รางวัลในรอบนั้น</li>
          <li>
            <b>แจ็กพอต 5,000 เหรียญ</b> ออกที่การหมุนแบบเสียเหรียญลำดับที่ {n(JACKPOT_EVERY_PAID_SPINS)}, {n(JACKPOT_EVERY_PAID_SPINS * 2)}, … ของผู้เล่นทุกคนรวมกัน (นับจากตัวนับกลาง)
            การหมุนฟรีไม่ถูกนับและไม่ได้แจ็กพอต
          </li>
          <li>เป็นเกมสุ่มโชค ไม่มีการรับประกันว่าจะได้รางวัลหรือได้กำไรในแต่ละรอบ กรุณาเล่นตามกำลังที่เหมาะสม</li>
        </RuleList>
      </RuleSection>

      <RuleSection title="3. การ์ด +ความเฮง">
        <RuleList>
          <li>การ์ดที่ได้จะเก็บไว้ในคลัง กด “ใช้การ์ด” เพื่อเปิดบัฟ <b>{BUFF_ROUNDS} รอบ</b> (ใช้ได้เมื่อมีสิทธิ์ฟรีหรือเหรียญพอสำหรับหมุน และเปิดซ้อนกันไม่ได้)</li>
          <li>ระหว่างบัฟ ทุกรอบการันตีว่าได้รางวัล และเพิ่มโอกาสได้ 400 เหรียญ บัฟไม่หมดตามเวลา และจะหมดเมื่อใช้ครบ {BUFF_ROUNDS} รอบ</li>
        </RuleList>
      </RuleSection>

      <RuleSection title={`4. โหมด “มือขึ้น ${HOT_STREAK_ROUNDS} ตาติด” 🔥`}>
        <RuleList>
          <li>หลังหมุนแบบเสียเหรียญ ระบบอาจสุ่มเข้าโหมดมือขึ้นได้เป็นครั้งคราว (ไม่ใช่ทุกคนหรือทุกครั้ง)</li>
          <li>ในโหมดนี้การหมุน <b>{HOT_STREAK_ROUNDS} รอบถัดไป</b> (ฟรีหรือเสียเหรียญ) มีโอกาสได้รางวัลเหรียญสูงขึ้น ประมาณ 80% ต่อรอบ</li>
          <li>เมื่อเข้าโหมดจะมีป้าย “🔥 มือขึ้น! เหลือ n/{HOT_STREAK_ROUNDS} รอบ” ขึ้นบนหน้าจอให้เห็นชัดเจน</li>
        </RuleList>
      </RuleSection>

      <RuleSection title="5. ยอดสะสมจากการหมุนเกม และการถอนเงิน">
        <RuleList>
          <li>
            ทุกครั้งที่หมุนแบบเสียเหรียญแล้วได้รางวัลเป็นเหรียญ (ไม่รวมแจ็กพอต) ระบบจะเพิ่ม <b>{WHEEL_CASH_PCT}% ของรางวัล</b> เข้า “ยอดสะสม” แยกต่างหาก
            โดยเหรียญรางวัลยังเข้ากระเป๋าตามปกติ การหมุนฟรีไม่เพิ่มยอดสะสม
          </li>
          <li>
            ยอดสะสมครบ <b>{n(WHEEL_CASH_SMALL)}</b> ถอนเป็นเงิน {n(WHEEL_CASH_SMALL)} บาทได้ (จำกัด <b>{WHEEL_CASH_LIMITS.perDay} ครั้งต่อวัน และ {WHEEL_CASH_LIMITS.perWeek} ครั้งต่อสัปดาห์</b> ตามเวลาไทย
            รายการที่รอตรวจหรืออนุมัติแล้วนับรวมในโควตา ถ้าถูกปฏิเสธจะคืนโควตา)
          </li>
          <li>ยอดสะสมครบ <b>{n(WHEEL_CASH_BIG)}</b> ถอนเป็นเงิน {n(WHEEL_CASH_BIG)} บาทได้ (ไม่มีโควตารายวัน แต่แอดมินตรวจสอบก่อนอนุมัติ)</li>
          <li>
            เมื่อกดขอถอน ระบบจะ <b>กันยอดสะสมตามขั้นที่เลือกไว้ทันที</b> เพื่อไม่ให้ขอซ้ำ มีได้ครั้งละ 1 รายการที่รอตรวจ หากแอดมินปฏิเสธ ยอดจะถูกคืนเข้ายอดสะสม
            การขอถอนไม่ได้หักเหรียญในกระเป๋าของคุณ
          </li>
        </RuleList>
      </RuleSection>

      <RuleSection title="6. การถอนรางวัลแจ็กพอต 5,000 บาท">
        <RuleList>
          <li>เมื่อได้แจ็กพอต จะได้สิทธิ์ถอน 1 สิทธิ์ ที่หน้า “ถอนรางวัล” ต้องมีเหรียญในกระเป๋าไม่น้อยกว่า 5,000 เหรียญ</li>
          <li>เมื่อกดขอถอน ระบบจะหัก 5,000 เหรียญและ 1 สิทธิ์ออกทันที (กันยอดไว้) หากแอดมินปฏิเสธ จะคืนเหรียญและสิทธิ์ให้ครบ</li>
        </RuleList>
      </RuleSection>

      <RuleSection title="7. ข้อมูลการรับเงินและการตรวจสอบ">
        <RuleList>
          <li>กรอกชื่อธนาคาร เลขบัญชี และชื่อบัญชีให้ถูกต้อง ชื่อบัญชีควรตรงกับเจ้าของบัญชีที่ลงทะเบียน หากข้อมูลผิดอาจโอนไม่สำเร็จ</li>
          <li>ทุกคำขอถอนผ่านการตรวจสอบโดยแอดมิน สถานะดูได้ที่หน้า “ถอนรางวัล” หากมีปัญหา ติดต่อแอดมินผ่านปุ่ม LINE</li>
          <li>ระบบสงวนสิทธิ์ปฏิเสธคำขอที่พบความผิดปกติ หรือมีการใช้งานไม่สุจริต</li>
        </RuleList>
      </RuleSection>
    </>
  );
}
