import { BONUS_TARGET, BONUS_WITHDRAW_THB } from "@/lib/lucky-card/bonus";
import { GUARANTEE_DRY_COINS, GUARANTEE_DRY_ROUNDS, GUARANTEE_EVERY_COINS, GUARANTEE_EVERY_ROUNDS } from "@/lib/lucky-card/guarantee";
import { RuleList, RuleSection } from "./RuleParts";

const n = (v: number) => v.toLocaleString("th-TH");

/** Rules of "ดวงดี มีเฮ" (the 8-card game). Numbers match the game; the guarantee numbers are pinned by a test. */
export function LuckyCardRules() {
  return (
    <>
      <RuleSection title="1. วิธีเล่นและค่าเล่น">
        <RuleList>
          <li>เปิดไพ่ 1 ใบจาก 8 ใบ ค่าเล่น <b>20 เหรียญต่อรอบ</b> ผลสุ่มและหักเหรียญที่ระบบหลังบ้านรอบละครั้ง ไพ่ทุกใบให้ผลสุ่มใหม่ทุกรอบ ไม่ว่าจะเลือกใบไหน</li>
          <li>เหรียญไม่พอ ระบบจะไม่เปิดไพ่และไม่หักเหรียญ ถ้าการเชื่อมต่อขัดข้องก่อนได้ผล เหรียญจะไม่ถูกหักซ้ำ</li>
          <li>เป็นเกมสุ่มโชค ไม่มีการรับประกันว่าจะได้รางวัลใหญ่ในแต่ละรอบ กรุณาเล่นตามกำลังที่เหมาะสม</li>
        </RuleList>
      </RuleSection>

      <RuleSection title="2. ผลที่อาจได้">
        <RuleList>
          <li><b>ข้อความมงคล</b> (ส่วนใหญ่ของรอบ): ให้กำลังใจและข้อคิด ไม่มีเหรียญ</li>
          <li><b>โบนัสเหรียญ</b> เข้ากระเป๋าทันที: โบนัสสุ่มระดับ 100 / 300 / 500 เหรียญ และโบนัสการันตีตามข้อ 3</li>
          <li><b>รางวัลลับ “เทพประทานทรัพย์”</b> มูลค่า 1,000 บาท ออกได้น้อยมาก เป็นสิทธิ์ถอนเป็นเงิน (ไม่เข้ากระเป๋าเป็นเหรียญ) เลือกถอนทันที หรือเก็บไว้ถอนทีหลังที่หน้า “ถอนรางวัล”</li>
        </RuleList>
      </RuleSection>

      <RuleSection title="3. ระบบการันตี 2 ขั้น">
        <RuleList>
          <li>
            <b>ทุก {GUARANTEE_DRY_ROUNDS} รอบที่ไม่ได้โบนัส:</b> ถ้าเปิดไพ่ {GUARANTEE_DRY_ROUNDS} รอบติดกันโดยไม่ได้โบนัสหรือรางวัลลับเลย
            รอบที่ {GUARANTEE_DRY_ROUNDS} จะได้โบนัส <b>{GUARANTEE_DRY_COINS} เหรียญ</b> และเริ่มนับใหม่ (ได้โบนัสเมื่อไหร่ ก็เริ่มนับใหม่เมื่อนั้น)
          </li>
          <li>
            <b>ทุกรอบที่ {GUARANTEE_EVERY_ROUNDS}:</b> นับต่อเนื่องจากทุกรอบที่เล่น (ได้โบนัสเองก็ไม่รีเซ็ต) รอบที่ {GUARANTEE_EVERY_ROUNDS}, {GUARANTEE_EVERY_ROUNDS * 2}, … ได้โบนัส <b>{GUARANTEE_EVERY_COINS} เหรียญ</b>
            ถ้าตรงกับขั้นแรกพร้อมกัน จะได้ขั้นนี้ (ใหญ่กว่า)
          </li>
          <li>การันตีใช้แทนเฉพาะรอบที่จะออกเป็นข้อความธรรมดา ถ้ารอบนั้นได้โบนัสหรือรางวัลลับอยู่แล้ว จะได้ตามนั้น</li>
          <li>หน้าเกมมีข้อความนับถอยหลัง “อีก N รอบ การันตีโบนัส …” แสดงให้เห็นตลอด</li>
        </RuleList>
      </RuleSection>

      <RuleSection title={`4. โบนัสสะสมครบ ${n(BONUS_TARGET)} เหรียญ ถอนเป็นเงิน ${n(BONUS_WITHDRAW_THB)} บาท`}>
        <RuleList>
          <li>โบนัสเหรียญทุกครั้ง (ทั้งสุ่มและการันตี) เข้ากระเป๋าตามปกติ <b>และ</b> นับเป็น “โบนัสสะสม” ของเกมนี้อีกทางหนึ่ง ดูแถบความคืบหน้าได้ที่หน้าเกม</li>
          <li>เมื่อโบนัสสะสมครบ {n(BONUS_TARGET)} เหรียญ กด “ถอน {n(BONUS_WITHDRAW_THB)} บาท” เพื่อกรอกข้อมูลบัญชีและส่งคำขอ</li>
          <li>
            เมื่อส่งคำขอ ระบบจะ <b>กันโบนัสสะสม {n(BONUS_TARGET)} ไว้ทันที</b> มีคำขอที่รอตรวจได้ครั้งละ 1 รายการ กดซ้ำหรือเปิดหลายหน้าจอไม่ทำให้ขอซ้ำ
            การขอถอนไม่ได้หักเหรียญในกระเป๋าของคุณ
          </li>
          <li>ถ้าแอดมินอนุมัติ จะโอนเงิน {n(BONUS_WITHDRAW_THB)} บาท ถ้าปฏิเสธ ระบบคืนโบนัสสะสม {n(BONUS_TARGET)} กลับให้ครบ</li>
          <li>ยังไม่อยากถอน เลือก “เก็บไว้ก่อน / ถอนทีหลัง” ได้ ยอดสะสมไม่หาย และกลับมากดถอนได้ทุกเมื่อ (ที่หน้าเกมหรือหน้า “ถอนรางวัล”)</li>
        </RuleList>
      </RuleSection>

      <RuleSection title="5. ข้อมูลการรับเงินและการตรวจสอบ">
        <RuleList>
          <li>กรอกชื่อธนาคาร เลขบัญชี และชื่อบัญชีให้ถูกต้อง หากข้อมูลผิดอาจโอนไม่สำเร็จ</li>
          <li>ทุกคำขอถอน (รวมรางวัลลับ) ผ่านการตรวจสอบโดยแอดมิน สถานะดูได้ที่หน้า “ถอนรางวัล” หากมีปัญหา ติดต่อแอดมินผ่านปุ่ม LINE</li>
          <li>รางวัลลับที่ถูกปฏิเสธจะคืนสิทธิ์ให้ถอนใหม่ได้ ระบบสงวนสิทธิ์ปฏิเสธคำขอที่พบความผิดปกติ หรือมีการใช้งานไม่สุจริต</li>
        </RuleList>
      </RuleSection>
    </>
  );
}
