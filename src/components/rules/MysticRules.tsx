import { BETS, EDGE_BP, MAX_PAYOUT, TILES } from "@/lib/mystic/config";
import { RuleList, RuleSection } from "./RuleParts";

const n = (v: number) => v.toLocaleString("th-TH");

/** Rules of เปิดหีบมนตรา. Numbers come from the constants the game uses (a test keeps the SQL in sync with them). */
export function MysticRules() {
  return (
    <>
      <RuleSection title="1. วิธีเล่น">
        <RuleList>
          <li>มีหีบ {TILES} ใบ (3×3) ซ่อน “จุดอาถรรพ์” ไว้ 1, 2 หรือ 3 จุด ตามที่คุณเลือก ยิ่งมีจุดอาถรรพ์มาก ตัวคูณยิ่งขึ้นเร็วแต่เสี่ยงขึ้น</li>
          <li>เลือกเดิมพัน {BETS.map((b) => n(b)).join(" / ")} เหรียญ ระบบหักเดิมพันตอนเริ่มรอบ แล้วเปิดหีบทีละใบ</li>
          <li>เปิดเจอหีบปลอดภัย ตัวคูณจะเพิ่มขึ้น และกด “รับเหรียญ” ได้ทุกเมื่อหลังเปิดปลอดภัยอย่างน้อย 1 ใบ</li>
          <li>เปิดเจอจุดอาถรรพ์ รอบจบทันทีและเสียเดิมพัน</li>
          <li>ถ้าเปิดหีบปลอดภัยครบทุกใบ หรือเงินรางวัลถึงเพดาน ระบบจ่ายเหรียญให้อัตโนมัติ</li>
        </RuleList>
      </RuleSection>

      <RuleSection title="2. ตัวคูณและโอกาส">
        <RuleList>
          <li>ตัวคูณคำนวณจากความน่าจะเป็นจริงของการเปิดหีบปลอดภัยติดกัน แล้วหักค่าดำเนินการ {EDGE_BP / 100}% ผลคืนเฉลี่ยของผู้เล่นจึงประมาณ {100 - EDGE_BP / 100}% ของเดิมพัน ไม่ว่าจะหยุดรับเหรียญที่หีบใบไหน</li>
          <li>ยอดรับเหรียญปัดเป็นเหรียญเต็ม (ปัดลง) ดังนั้นเดิมพันน้อยอาจได้ผลคืนต่ำกว่าค่าเฉลี่ยเล็กน้อย</li>
          <li>ตำแหน่งจุดอาถรรพ์ถูกสุ่มโดยระบบหลังบ้านตอนเริ่มรอบและเปลี่ยนไม่ได้ ไม่มีวิธีเลือกหีบให้ปลอดภัยกว่า</li>
          <li>ตารางตัวคูณของแต่ละระดับดูได้ที่หน้าเริ่มรอบก่อนกดเริ่มเล่น</li>
        </RuleList>
      </RuleSection>

      <RuleSection title="3. เพดานรางวัลและเงื่อนไขอื่น">
        <RuleList>
          <li>รับเหรียญได้สูงสุด <b>{n(MAX_PAYOUT)} เหรียญต่อรอบ</b> หากตัวคูณทำให้เกินเพดาน ระบบจ่ายที่เพดานและจบรอบให้อัตโนมัติ</li>
          <li>มีรอบที่ยังเล่นค้างได้ครั้งละ 1 รอบ หากออกจากหน้าเกมกลางคันหรือเน็ตหลุด กลับมาแล้วจะเล่นรอบเดิมต่อได้ ไม่หักเหรียญซ้ำ</li>
          <li>เหรียญรางวัลเข้ากระเป๋าหลักทั้งหมด ไม่มีระบบถอนเป็นเงินโดยตรงจากเกมนี้</li>
          <li>เป็นเกมเสี่ยงโชค มีโอกาสเสียเดิมพันทั้งหมดในแต่ละรอบ กรุณาเล่นตามกำลังที่เหมาะสม หากพบปัญหา ติดต่อแอดมินผ่านปุ่ม LINE</li>
        </RuleList>
      </RuleSection>
    </>
  );
}
