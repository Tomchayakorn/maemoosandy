import { BETS, EDGE_BP, MAX_LEVEL, MAX_PAYOUT, SLICES } from "@/lib/power-wheel/config";
import { RuleList, RuleSection } from "./RuleParts";

const n = (v: number) => v.toLocaleString("th-TH");

/** Rules of วงล้อไต่ชั้น. Numbers come from the constants the game uses (a test keeps the SQL in sync with them). */
export function PowerWheelRules() {
  return (
    <>
      <RuleSection title="1. วิธีเล่น">
        <RuleList>
          <li>เลือกเดิมพัน {BETS.map((b) => n(b)).join(" / ")} เหรียญ ระบบหักเดิมพันตอนเริ่มรอบ แล้วหมุนวงล้อ {SLICES} ช่องทีละชั้น รวม {MAX_LEVEL} ชั้น</li>
          <li>หมุนได้ช่อง ✨ = ผ่านชั้นนั้นและพลังสะสม (ตัวคูณ) เพิ่มขึ้น หมุนได้ช่อง 💀 = รอบจบทันทีและเสียเดิมพัน</li>
          <li>ยิ่งชั้นสูง ช่อง 💀 ยิ่งมาก (เริ่มที่ 1 ช่อง และเพิ่มเป็น 6 ช่องในชั้นบนสุด) จำนวนช่อง 💀 ของแต่ละชั้นแสดงบนวงล้อให้เห็นก่อนหมุนทุกครั้ง</li>
          <li>หลังผ่านอย่างน้อย 1 ชั้น กด “หยุดและรับเหรียญ” ได้ทุกเมื่อ หรือเสี่ยงหมุนต่อเพื่อไต่ขึ้นชั้นถัดไป</li>
          <li>ถ้าไต่ถึงชั้นสูงสุด หรือรางวัลสะสมถึงโบนัสสูงสุดต่อรอบ ระบบจ่ายเหรียญเข้ากระเป๋าให้อัตโนมัติ</li>
        </RuleList>
      </RuleSection>

      <RuleSection title="2. ตัวคูณและโอกาส">
        <RuleList>
          <li>ตัวคูณคำนวณจากความน่าจะเป็นจริงของการผ่านชั้นติดกัน แล้วหักค่าดำเนินการ {EDGE_BP / 100}% ผลคืนเฉลี่ยของผู้เล่นจึงประมาณ {100 - EDGE_BP / 100}% ของเดิมพัน ไม่ว่าจะหยุดรับเหรียญที่ชั้นไหน</li>
          <li>ยอดรับเหรียญปัดเป็นเหรียญเต็ม (ปัดลง) ดังนั้นเดิมพันน้อยอาจได้ผลคืนต่ำกว่าค่าเฉลี่ยเล็กน้อย</li>
          <li>ช่องที่วงล้อหยุดถูกสุ่มโดยระบบหลังบ้านทุกครั้งและเปลี่ยนไม่ได้ ไม่มีจังหวะหรือวิธีกดที่ทำให้โชคดีกว่า</li>
          <li>ตารางตัวคูณของแต่ละชั้นแสดงบนบันไดชั้นของเกม</li>
        </RuleList>
      </RuleSection>

      <RuleSection title="3. โบนัสสูงสุดและเงื่อนไขอื่น">
        <RuleList>
          <li><b>โบนัสสูงสุดต่อรอบ ({n(MAX_PAYOUT)} เหรียญ)</b> หากตัวคูณทำให้รางวัลสะสมเกินนี้ ระบบจ่ายที่ {n(MAX_PAYOUT)} เหรียญและจบรอบให้อัตโนมัติ</li>
          <li>มีรอบที่ยังเล่นค้างได้ครั้งละ 1 รอบ หากออกจากหน้าเกมกลางคันหรือเน็ตหลุด กลับมาแล้วจะเล่นรอบเดิมต่อได้ ไม่หักเหรียญซ้ำ</li>
          <li>รางวัลสะสมเข้ากระเป๋าเหรียญทันทีเมื่อกดรับเหรียญหรือรอบจบแบบได้รางวัล ระบบจะแสดงข้อความยืนยันให้เห็น</li>
          <li>เหรียญรางวัลใช้ในระบบเท่านั้น ไม่ใช่รางวัลถอนเงิน และเกมนี้ไม่มีการถอนเป็นเงิน ไม่ใช้สิทธิ์หมุนฟรี และแยกจากกงล้อหลักทั้งหมด</li>
          <li>เป็นเกมเสี่ยงโชค มีโอกาสเสียเดิมพันทั้งหมดในแต่ละรอบ กรุณาเล่นตามกำลังที่เหมาะสม หากพบปัญหา ติดต่อแอดมินผ่านปุ่ม LINE</li>
        </RuleList>
      </RuleSection>
    </>
  );
}
